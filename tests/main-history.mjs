import assert from 'node:assert/strict';
import {validate} from '../public/validate.js';
import {activeMain,changeMain,normalizeMainHistory,mainHistoryMarkup} from '../public/main-paddle.js';
const paddles=[{id:'a',brand:'A',model:'One',status:'active'},{id:'b',brand:'B',model:'Two',status:'active'}];
const base={version:2,paddles,sessions:[],usagePeriods:[],settings:{singlesMainPaddleId:'b'}};
const migrated=validate(base);
assert.equal(migrated.settings.mainPaddleId,'b');
assert.equal(migrated.settings.mainPaddleHistory[0].start,null);
assert.deepEqual(validate(migrated),migrated);
assert.equal(activeMain(paddles,{mainPaddleId:'a',singlesMainPaddleId:'b'}),'a');
assert.equal(activeMain([]),null);
let settings=changeMain(migrated.settings,'a','2026-01-01T00:00:00Z');
settings=changeMain(settings,'b','2026-01-03T00:00:00Z');
assert.deepEqual(changeMain(settings,'b'),settings);
assert.equal(settings.mainPaddleHistory[1].end,'2026-01-03T00:00:00Z');
const markup=mainHistoryMarkup(settings,paddles,p=>p.model,x=>x,Date.parse('2026-01-04T00:00:00Z'));
assert.match(markup,/2.0 recorded days/);assert.match(markup,/Start date unknown/);assert.match(markup,/Current Main/);
const archived=validate({...base,paddles:paddles.map(p=>({...p,status:p.id==='b'?'archived':'active'})),settings});
assert.equal(archived.settings.mainPaddleId,'a');
assert.equal(archived.settings.mainPaddleHistory.filter(r=>r.end===null).length,1);
assert.deepEqual(validate(archived),archived);
const deleted=validate({...base,paddles:[paddles[0]],settings:{...settings,mainPaddleId:null,singlesMainPaddleId:null}});
assert.equal(deleted.settings.mainPaddleId,'a');assert.equal(deleted.settings.mainPaddleHistory.filter(r=>r.end===null).length,1);
assert.throws(()=>normalizeMainHistory([{id:'x',paddleId:'a',start:123,end:null}]));
assert.throws(()=>normalizeMainHistory([{id:'x',paddleId:'a',start:null,end:null},{id:'y',paddleId:'b',start:null,end:null}]));
console.log('Main history migration, transitions, totals, archive and deletion passed.');
