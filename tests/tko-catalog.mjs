import assert from 'node:assert/strict';
import fs from 'node:fs';
import {normalizeSharedCatalog} from '../public/shared-catalog.js';
import {modelApproval} from '../public/competition.js';
const catalog=JSON.parse(fs.readFileSync('public/reference-catalog.json'));
const rows=normalizeSharedCatalog(catalog);
const row=rows.find(x=>x.brand==='Paddletek'&&x.model==='Bantam TKO-C 12.7mm');
assert.ok(row);
assert.equal(row.thickness,12.7);
assert.equal(row.shape,'Elongated');
assert.equal(row.modelNumber,'TKO-C12');
assert.deepEqual(row.referenceRecord.specs.staticWeightOzRange,{min:7.7,max:8.1});
assert.equal(row.reference.values.staticWeight,undefined);
assert.equal(row.reference.values.length,16.5);
const data=JSON.parse(fs.readFileSync('public/competition-data.json'));
const paddle={brand:row.brand,model:row.model,modelId:row.referenceModelId,thickness:12.7};
const now=Date.parse('2026-10-03T12:00:00Z');
assert.equal(modelApproval(paddle,data.rulesets.find(x=>x.id==='usap'),data,now).status,'APPROVED');
for(const rule of data.rulesets.filter(x=>x.organization==='UPA-A'))assert.notEqual(modelApproval(paddle,rule,data,now).status,'APPROVED');
assert.ok(rows.some(x=>x.brand==='Paddletek'&&x.model==='TKO-CX2 12.7mm'&&x.referenceModelId!==row.referenceModelId));
console.log('PASS: exact TKO-C 12.7 catalog identity, manufacturer ranges, USAP approval, and distinct CX2 identity.');
