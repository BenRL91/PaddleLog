import assert from 'node:assert/strict';
import fs from 'node:fs';
import {Window} from 'happy-dom';
import {productName,customerVariant} from '../public/catalog-names.js';
import {createCatalogTools} from '../public/catalog-ui.js';
import {normalizeSharedCatalog} from '../public/shared-catalog.js';
import {catalogKey} from '../public/catalog.js';
const rows=normalizeSharedCatalog(JSON.parse(fs.readFileSync('public/reference-catalog.json')));
const boom=rows.filter(r=>/^Project Boomstik/i.test(r.model));
assert.equal(productName(boom.find(r=>r.model==='Project Boomstik Widebody 16mm')),'Boomstik');
assert.equal(productName(boom.find(r=>/Widebody Raw Carbon 16mm/.test(r.model))),'Boomstik Raw Carbon');
assert.notEqual(productName({model:'Perseus 3S 16mm'}),productName({model:'Perseus 3S Dual 16mm'}));
assert.notEqual(productName({model:'Perseus Pro V 16mm'}),productName({model:'Perseus IV 16mm'}));
const win=new Window();win.document.write(fs.readFileSync('app/paddle.html','utf8').replace(/<script[\s\S]*?<\/script>/g,''));const doc=win.document;
const ui=createCatalogTools({doc,getState:()=>({catalog:boom}),confirm:async()=>true,onDraft(){},onApplied(){},saveCatalog:async()=>true});
doc.getElementById('brand').value='Selkirk Sport';ui.refresh();
assert.equal(doc.getElementById('modelCatalog').options.length,3);
doc.getElementById('modelCatalog').value='Boomstik';doc.getElementById('modelCatalog').dispatchEvent(new win.Event('change'));
assert.equal(doc.getElementById('model').value,'');assert.equal(doc.getElementById('catalogModelId').value,'');
assert.ok([...doc.getElementById('catalogVariant').options].slice(1).every(o=>!o.text.includes('Project Boomstik')));
const selected=boom.find(r=>r.model==='Project Boomstik Widebody 16mm');doc.getElementById('catalogVariant').value=catalogKey(selected);doc.getElementById('catalogVariant').dispatchEvent(new win.Event('change'));await new Promise(r=>setTimeout(r,0));
assert.equal(doc.getElementById('model').value,selected.model);assert.equal(doc.getElementById('catalogModelId').value,selected.referenceModelId);ui.refresh();assert.equal(doc.getElementById('modelCatalog').value,'Boomstik');
assert.match(doc.getElementById('catalogReference').textContent,/Project Boomstik Widebody 16mm/);
assert.match(customerVariant(selected),/Widebody.*16 mm.*InfiniGrit/);
await win.happyDOM.abort();console.log('PASS: product grouping, separate generations/surfaces, explicit exact variant selection, preserved identity and readable provenance.');
