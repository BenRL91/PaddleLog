import assert from 'node:assert/strict';
import {sessionUsage,componentWear,estimateContribution} from '../public/maintenance.js';
import {validate} from '../public/validate.js';
import {mergeChanges} from '../public/sync.js';
const at=h=>new Date(Date.UTC(2026,8,1)+h*36e5).toISOString();
const p={id:'p',brand:'A',model:'B',maintenance:['overgrip','edgeTape','skin'].map(kind=>({id:kind,kind,action:'install',at:at(0),interval:4}))};
const e={id:'e',paddleId:'p',start:at(0),end:at(24),estimatedHours:8};
const s={id:'s',paddleId:'p',start:at(0),end:at(2)};
assert.equal(sessionUsage('p',[]),0);assert.equal(sessionUsage('p',[e]),8);
for(const kind of ['overgrip','edgeTape','skin'])assert.equal(componentWear(p,[e],kind).label,'Used');
assert.equal(sessionUsage('p',[e,s]),8);assert.equal(estimateContribution(e,[e,s]),6);
assert.equal(sessionUsage('p',[e,{...s,end:at(10)}]),10);assert.equal(sessionUsage('p',[e,{...s,end:at(1)}]),8);assert.equal(sessionUsage('p',[e]),8);
assert.equal(sessionUsage('p',[e],Date.parse(at(12))),4);
assert.ok(Math.abs(sessionUsage('p',[e,s],Date.parse(at(12)))-6*12/22)<1e-9);
const replaced={...p,maintenance:[...p.maintenance,{id:'replace',kind:'overgrip',action:'install',at:at(24),interval:4}]};
assert.equal(componentWear(replaced,[e,s],'overgrip').hours,0);assert.equal(componentWear(replaced,[e,s],'skin').hours,8);assert.equal(sessionUsage('p',[e,s]),8);
const data={version:2,paddles:[p],sessions:[e,s],usagePeriods:[{id:'old',paddleId:'p',start:'2026-01-01',end:'2026-02-01'}]};
const clean=validate(data);assert.equal(clean.usageSchema,1);assert.deepEqual(validate(JSON.parse(JSON.stringify(clean))),clean);
assert.throws(()=>validate({...data,sessions:[e,{...e,id:'overlap',start:at(12)}]}),/overlap/i);
for(const estimatedHours of [0,-1,25,NaN,Infinity,'8'])assert.throws(()=>validate({...data,sessions:[{...e,estimatedHours}]}));
assert.doesNotThrow(()=>validate({...data,sessions:[e,{...e,id:'adjacent',start:at(24),end:at(48)}]}));
const base=validate({...data,sessions:[]}),left=validate({...data,sessions:[e]}),right=validate({...data,sessions:[s]});
assert.equal(sessionUsage('p',validate(mergeChanges(base,left,right)).sessions),8);
assert.equal(componentWear(p,[{...e,estimatedHours:3}],'skin').label,'Brand New');assert.equal(componentWear(p,[{...e,estimatedHours:5}],'skin').label,'New');assert.equal(componentWear(p,[],'skin').hours,0);
console.log('PASS: estimates replace logged overlap, installation allocation, independent resets, stages forward/backward, safe validation, JSON roundtrip and concurrent merge.');
